let current: Strings = zh;

export function setLanguage(pref: "auto" | "zh" | "en") {
	let lang: string = pref;
	if (pref === "auto") {
		const ui = (getLanguage() || "en").toLowerCase();
		lang = ui.startsWith("zh") ? "zh" : "en";
	}
	current = lang === "zh" ? zh : en;
}

export function t(): Strings {
	return current;
}

export function isZh(): boolean {
	return current === zh;
}
